"""T-02 regression tests for the taxonomy alias review CSV.

The CSV is an audit artifact generated by
``backend/scripts/migrate/build_taxonomy_v2.py make-aliases``. These tests only
read the generated file; they do not touch the database.
"""
from __future__ import annotations

import ast
import csv
from pathlib import Path

import pytest

BACKEND_DIR = Path(__file__).resolve().parents[1]
CSV_PATH = BACKEND_DIR / "data" / "audit" / "taxonomy_alias_review.csv"
SEED_PATH = BACKEND_DIR / "scripts" / "admin" / "seed.py"

EXPECTED_COLUMNS = [
    "old_id",
    "old_name",
    "subject",
    "sub_category",
    "new_id",
    "new_name",
    "match_type",
    "confidence",
    "note",
]
ALLOWED_MATCH_TYPES = {"exact", "alias", "subcategory_other", "hidden"}
ALLOWED_SUBJECTS = {"行测", "申论", "公专"}
LEGACY_IDS = set(range(127, 632))


def load_rows() -> list[dict]:
    assert CSV_PATH.exists(), f"missing generated CSV: {CSV_PATH}"
    with CSV_PATH.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        assert reader.fieldnames == EXPECTED_COLUMNS
        return list(reader)


def load_canonical_tree() -> dict:
    module = ast.parse(SEED_PATH.read_text(encoding="utf-8"))
    for node in module.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id == "KNOWLEDGE_TREE_V2":
                return ast.literal_eval(node.value)
    raise AssertionError("KNOWLEDGE_TREE_V2 not found in seed.py")


@pytest.fixture(scope="module")
def rows() -> list[dict]:
    return load_rows()


def test_has_exactly_505_rows(rows):
    assert len(rows) == 505


def test_all_headings_present(rows):
    # DictReader already asserted the exact field order in load_rows(), but keep
    # an explicit guard for direct consumers of the fixture.
    assert list(rows[0].keys()) == EXPECTED_COLUMNS


def test_match_type_values(rows):
    bad = {row["match_type"] for row in rows} - ALLOWED_MATCH_TYPES
    assert not bad, f"unexpected match_type values: {bad}"


def test_hidden_rows_have_notes(rows):
    missing = [
        row["old_id"]
        for row in rows
        if row["match_type"] == "hidden" and not row["note"].strip()
    ]
    assert not missing, f"hidden rows without note: {missing}"


def test_non_hidden_rows_have_new_name(rows):
    missing = [
        row["old_id"]
        for row in rows
        if row["match_type"] != "hidden" and not row["new_name"].strip()
    ]
    assert not missing, f"non-hidden rows without new_name: {missing}"


def test_subcategory_other_rows_document_heuristic(rows):
    missing = [
        row["old_id"]
        for row in rows
        if row["match_type"] == "subcategory_other" and not row["note"].strip()
    ]
    assert not missing, f"subcategory_other rows without heuristic note: {missing}"


def test_old_ids_unique_and_cover_legacy_range(rows):
    old_ids = [int(row["old_id"]) for row in rows]
    assert len(old_ids) == len(set(old_ids)), "duplicate old_id values"
    assert set(old_ids) == LEGACY_IDS


def test_subject_and_confidence_values(rows):
    for row in rows:
        assert row["subject"] in ALLOWED_SUBJECTS, row
        confidence = float(row["confidence"])
        assert 0.0 <= confidence <= 1.0, row


def test_new_names_are_canonical_l3(rows):
    tree = load_canonical_tree()
    canonical_l3 = {
        subject: {
            l3
            for groups in tree[subject].values()
            for l3s in groups.values()
            for l3 in l3s
        }
        for subject in tree
    }
    bad = [
        row
        for row in rows
        if row["match_type"] != "hidden"
        and row["new_name"] not in canonical_l3.get(row["subject"], set())
    ]
    assert not bad, f"new_name is not a canonical L3: {bad[:5]}"
