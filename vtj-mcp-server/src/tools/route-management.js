/**
 * 向路由内容字符串中添加静态路由
 * @param {string} content 原始路由文件内容
 * @param {object} route 路由配置 { path, name, componentPath }
 * @returns {{success: boolean, content?: string, error?: string}}
 */
export function addStaticRoute(content, { path, name, componentPath }) {
  // 检查路由是否已存在
  if (content.includes(`path: '${path}'`) || content.includes(`path: "${path}"`)) {
    return { success: false, error: 'ROUTE_DUPLICATE' };
  }

  // 在最后一个路由条目后插入
  const lastRouteIndex = content.lastIndexOf('},\n');
  if (lastRouteIndex === -1) {
    return { success: false, error: 'ROUTE_PARSE_ERROR' };
  }

  const newRoute = `  {\n    path: '${path}',\n    name: '${name}',\n    component: () => import('${componentPath}')\n  }`;

  const before = content.substring(0, lastRouteIndex + 2);
  const after = content.substring(lastRouteIndex + 2);
  const newContent = before + ',\n' + newRoute + after;

  return { success: true, content: newContent };
}

// ── 处理器 ──────────────────────────────────────────────

export const handlers = {
  async vtj_get_routing_info() {
    const project = getProjectConfig();
    const staticRouter = readText(getSrcRouterFile());
    const vtjRouter = readText(getVtjRouterFile());

    // 解析静态路由
    const staticRoutes = [];
    if (staticRouter) {
      const routeRegex = /\{\s*path\s*:\s*['"]([^'"]+)['"]\s*,\s*name\s*:\s*['"]([^'"]+)['"]\s*,\s*\n?\s*component\s*:\s*\(\)\s*=>\s*import\(['"]([^'"]+)['"]\)/g;
      let match;
      while ((match = routeRegex.exec(staticRouter)) !== null) {
        staticRoutes.push({
          path: match[1],
          name: match[2],
          component: match[3]
        });
      }
    }

    // VTJ 自动路由
    const autoRoutes = (project?.pages || []).map(p => ({
      path: `/page/${p.id}`,
      name: p.name,
      title: p.title,
      autoGenerated: true
    }));

    return createSuccessResponse({
      staticRoutesCount: staticRoutes.length,
      autoRoutesCount: autoRoutes.length,
      staticRoutes,
      autoRoutes,
      vtjRouterContent: vtjRouter,
      projectHomepage: project?.homepage || ''
    });
  },

  async vtj_add_route({ path, name, componentPath, dryRun = false }) {
    const srcRouterPath = getSrcRouterFile();
    if (!existsFile(srcRouterPath)) {
      return createErrorResponse('ROUTE_FILE_NOT_FOUND', '路由文件不存在: src/router/index.ts');
    }

    const content = readText(srcRouterPath);
    if (!content) {
      return createErrorResponse('ROUTE_FILE_NOT_FOUND', '无法读取路由文件');
    }

    if (dryRun) {
      return createDryRunPreview({
        operation: 'add_route',
        target: `src/router/index.ts`,
        changes: { path, name, componentPath },
        nextSteps: getNextSteps('add_route', path)
      });
    }

    const result = addStaticRoute(content, { path, name, componentPath });

    if (!result.success) {
      return createErrorResponse(result.error, result.error === 'ROUTE_DUPLICATE'
        ? `路由路径 "${path}" 已存在`
        : '无法解析路由文件');
    }

    // 备份
    writeText(srcRouterPath + '.bak', content);

    const success = writeText(srcRouterPath, result.content);
    if (!success) {
      return createErrorResponse('FILE_WRITE_ERROR', '写入路由文件失败');
    }

    return createSuccessResponse({
      path,
      name,
      componentPath,
      message: '路由已添加。重启开发服务器生效。'
    });
  }
};
